/// One thing the API test mod must see before it logs `apitest ok`, in the order a run sees them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Step {
    Listening,
    ModsLoaded,
    ProviderReady,
    FrameGate,
    TitleScreen,
    WorldJoined,
    ClientReads,
    HudHidden,
    HudShown,
    MouseReleased,
    MouseCaptured,
    KeyInput,
    KeyHeld,
    PlayerMove,
    MoveIntent,
    Turn,
    Wheel,
    Click,
    ClickX1,
    ClickX2,
    GamepadSkipped,
    PauseOpened,
    FramesPresented,
    OverlayBound,
    ShotGameOnly,
    ShotWithOverlays,
    Capture,
    RequestSize,
    WindowSize,
    Resized,
    WindowPointer,
    WindowChar,
    FrameCost,
}

impl Step {
    /// Every step, in run order.
    pub const ALL: [Self; 33] = [
        Self::Listening,
        Self::ModsLoaded,
        Self::ProviderReady,
        Self::FrameGate,
        Self::TitleScreen,
        Self::WorldJoined,
        Self::ClientReads,
        Self::HudHidden,
        Self::HudShown,
        Self::MouseReleased,
        Self::MouseCaptured,
        Self::KeyInput,
        Self::KeyHeld,
        Self::PlayerMove,
        Self::MoveIntent,
        Self::Turn,
        Self::Wheel,
        Self::Click,
        Self::ClickX1,
        Self::ClickX2,
        Self::GamepadSkipped,
        Self::PauseOpened,
        Self::FramesPresented,
        Self::OverlayBound,
        Self::ShotGameOnly,
        Self::ShotWithOverlays,
        Self::Capture,
        Self::RequestSize,
        Self::WindowSize,
        Self::Resized,
        Self::WindowPointer,
        Self::WindowChar,
        Self::FrameCost,
    ];

    /// The overlay and window steps: the draw, screenshots, capture stream and size request of the mod,
    /// the window events of the in-game task's resizes, click and character, and the frame times with and
    /// without the drawing listener.
    pub const OVERLAY: [Self; 11] = [
        Self::FramesPresented,
        Self::OverlayBound,
        Self::ShotGameOnly,
        Self::ShotWithOverlays,
        Self::Capture,
        Self::RequestSize,
        Self::WindowSize,
        Self::Resized,
        Self::WindowPointer,
        Self::WindowChar,
        Self::FrameCost,
    ];

    /// The name in the `apitest waiting` line.
    pub fn name(self) -> &'static str {
        match self {
            Self::Listening => "listening",
            Self::ModsLoaded => "mods_loaded",
            Self::ProviderReady => "provider_ready",
            Self::FrameGate => "frame_gate",
            Self::TitleScreen => "title_screen",
            Self::WorldJoined => "world_joined",
            Self::ClientReads => "client_reads",
            Self::HudHidden => "hud_hidden",
            Self::HudShown => "hud_shown",
            Self::MouseReleased => "mouse_released",
            Self::MouseCaptured => "mouse_captured",
            Self::KeyInput => "key_input",
            Self::KeyHeld => "key_held",
            Self::PlayerMove => "player_move",
            Self::MoveIntent => "move_intent",
            Self::Turn => "turn",
            Self::Wheel => "wheel",
            Self::Click => "click",
            Self::ClickX1 => "click_x1",
            Self::ClickX2 => "click_x2",
            Self::GamepadSkipped => "gamepad_skipped",
            Self::PauseOpened => "pause_opened",
            Self::FramesPresented => "frames_presented",
            Self::OverlayBound => "overlay_bound",
            Self::ShotGameOnly => "shot_game_only",
            Self::ShotWithOverlays => "shot_with_overlays",
            Self::Capture => "capture",
            Self::RequestSize => "request_size",
            Self::WindowSize => "window_size",
            Self::Resized => "resized",
            Self::WindowPointer => "window_pointer",
            Self::WindowChar => "window_char",
            Self::FrameCost => "frame_cost",
        }
    }

    pub(crate) fn bit(self) -> u64 {
        1 << (self as u64)
    }
}
